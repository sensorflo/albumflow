"""Tab completion scripts for shells, generated from albumflow's argparse setup.

Only commands and options (and the choices of positional arguments) are
completed; values such as album names are not. The script is static: it has
to be generated again when the commands change (the PowerShell profile does
that automatically when cli.py is newer than the cached script).

Reads argparse internals (_actions, _SubParsersAction, _choices_actions),
which have been stable for many years.
"""

from __future__ import annotations

import argparse

POWERSHELL = r"""# Tab completion for COMMANDS.
# Generated by "albumflow completion powershell"; don't edit, it is overwritten.

$global:AlbumflowCompletion = @{
TABLE
}

Register-ArgumentCompleter -Native -CommandName COMMANDS -ScriptBlock {
    param($wordToComplete, $commandAst, $cursorPosition)
    $words = @($commandAst.CommandElements | ForEach-Object { $_.ToString() })
    # The command is the first word after the program name, unless that is the word being completed.
    $sub = ''
    if ($words.Count -gt 2 -or ($words.Count -eq 2 -and $wordToComplete -eq '')) { $sub = $words[1] }
    $candidates = $global:AlbumflowCompletion[$sub]
    if ($null -eq $candidates) { return }
    if ($sub -ne '' -and $wordToComplete -ne '' -and -not $wordToComplete.StartsWith('-')) { return }  # e.g. an album
    foreach ($c in $candidates) {
        if ($c[0] -like "$wordToComplete*") {
            $type = if ($c[0].StartsWith('-')) { 'ParameterName' } else { 'ParameterValue' }
            [System.Management.Automation.CompletionResult]::new($c[0], $c[0], $type, $c[1])
        }
    }
}
"""


def _quote(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def _entries(parser: argparse.ArgumentParser) -> list[tuple[str, str]]:
    """(word, description) for the options and positional choices of a parser."""
    out = []
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction) or action.help == argparse.SUPPRESS:
            continue
        description = " ".join((action.help or "").split())
        for option in action.option_strings:
            out.append((option, description or option))
        if not action.option_strings and action.choices:
            out += [(str(choice), description or str(choice)) for choice in action.choices]
    return out


def table(parser: argparse.ArgumentParser) -> dict[str, list[tuple[str, str]]]:
    """'' -> commands and top-level options; each command (and alias) -> its options."""
    sub = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    helps = {id(sub.choices[c.dest]): " ".join((c.help or "").split()) for c in sub._choices_actions}
    result = {"": [(name, helps.get(id(p)) or name) for name, p in sub.choices.items()] + _entries(parser)}
    for name, p in sub.choices.items():
        result[name] = _entries(p)
    return result


def powershell(parser: argparse.ArgumentParser, commands: list[str]) -> str:
    rows = []
    for key, entries in table(parser).items():
        items = ", ".join(f"@({_quote(word)}, {_quote(text)})" for word, text in entries)
        rows.append(f"    {_quote(key)} = @({items})")
    return (POWERSHELL.replace("TABLE", "\n".join(rows))
            .replace("COMMANDS", ", ".join(_quote(c) for c in commands)))
